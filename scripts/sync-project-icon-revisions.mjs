// Derive URL revisions from the exact authored SVG bytes. The vector pack
// must agree before a release can publish any icon revision.
import {readFileSync,writeFileSync} from "node:fs";
import {createHash} from "node:crypto";
import assert from "node:assert/strict";
import {fileURLToPath} from "node:url";
const assets=new URL("../sites/_apex/assets/",import.meta.url);
const packed=JSON.parse(readFileSync(new URL("home-dashboard/continuous-icon-vectors.json",assets)));
const revisions={};
for(const name of Object.keys(packed.assets).sort()){
 const svg=readFileSync(new URL("project-icons/"+name+".svg",assets));
 const hash=createHash("sha256").update(svg).digest("hex");
 assert.equal(packed.assets[name].sourceSha256,hash,"Regenerate continuous vector geometry for "+name+" before publishing");
 assert.deepEqual(readFileSync(new URL("../app/assets/project-icons/"+name+".svg",assets)),svg,"Private SVG must match public "+name);
 revisions[name]=hash;
}
const output=new URL("project-icon-revisions.js",assets);
const generated="// Generated by scripts/sync-project-icon-revisions.mjs. Do not edit.\nexport const PROJECT_ICON_REVISIONS=Object.freeze("+JSON.stringify(revisions,null,2)+");\n";
if(process.argv.includes("--check")){
 assert.equal(readFileSync(output,"utf8"),generated,"Run node scripts/sync-project-icon-revisions.mjs after updating icons");
}else writeFileSync(output,generated);
console.log("Verified "+Object.keys(revisions).length+" authored SVG revisions against packed vector geometry");
